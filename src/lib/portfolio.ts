/**
 * Sites livrés par le studio, montrés en vitrine.
 *
 * Uniquement des projets réellement conçus par Bloomy Studio, jamais une
 * boutique partenaire de la marketplace bloomy.one (règle produit : aucune
 * preuve inventée). Trois natures :
 *   - `client`  : site livré à un client réel, en ligne à son adresse.
 *   - `recent`  : site conçu pour une entreprise réelle, montré depuis son
 *     adresse de travail ; sa mise en production n'est pas confirmée, donc il
 *     s'affiche « Projet récent », jamais « Site en ligne ».
 *   - `concept` : démonstration (entreprise fictive) ou proposition de refonte
 *     non commandée. Toujours « Projet concept », jamais un travail livré.
 *
 * Adresses : seule l'adresse propre d'une entreprise (son nom de domaine)
 * s'affiche en clair. Une adresse de développement (vercel.app, web.app,
 * pages.dev…) sert aux liens mais n'est jamais écrite à l'écran : voir
 * `siteHost` (demande de l'équipe, 2026-10-13).
 *
 * Les captures sont produites depuis les sites en ligne par
 * `npm run captures` (voir `scripts/capture-realisations.mjs`) : desktop
 * 1600 × 1000, mobile 390 × 844 en densité 2, et une capture longue de la
 * page entière (`long/`). Régénérer après toute refonte d'un site.
 *
 * `note` décrit ce qui est visible sur la capture : ce que le site fait, ce
 * qu'on a dessiné. Jamais une métrique — aucun chiffre de trafic ou de vente
 * n'est mesuré ni autorisé à ce jour.
 */

