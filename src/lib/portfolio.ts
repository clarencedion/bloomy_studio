/**
 * Hébergements de développement : leurs adresses ne sont jamais affichées
 * (« la plupart sont des liens de dev », équipe, 2026-10-13).
 */
const DEV_HOSTS = [".vercel.app", ".web.app", ".firebaseapp.com", ".pages.dev", ".netlify.app"];

/** Vrai si l'adresse est celle d'un hébergement de développement. */
export function isDevUrl(url: string): boolean {
  const host = new URL(url).hostname;
  return DEV_HOSTS.some((suffix) => host.endsWith(suffix));
}

/**
 * Ce qu'on affiche pour situer un projet (barre d'adresse des cadres,
 * légendes) : son nom de domaine quand c'est le sien, sinon son nom. Une
 * adresse de développement n'est jamais écrite à l'écran.
 */
export function siteHost(site: Pick<ShowcaseSite, "liveUrl" | "name">): string {
  if (isDevUrl(site.liveUrl)) return site.name;
  return new URL(site.liveUrl).hostname;
}


export function getShowcaseSite(slug: ShowcaseSlug): ShowcaseSite | undefined {
  return showcaseSites.find((s) => s.slug === slug);
}

/** Filtrer les sites par catégorie. */
export function getSitesByCategory(category: PortfolioCategory): readonly ShowcaseSite[] {
  if (category === "all") return showcaseSites;
  return showcaseSites.filter((s) =>
    (s.categories as readonly PortfolioCategory[]).includes(category),
  );
}
